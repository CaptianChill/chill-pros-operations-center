function bearer(req) {
  const match = String(req.headers.authorization || "").match(/^Bearer\s+(.+)$/i);
  return match ? match[1] : "";
}

function parseBody(req) {
  if (req.body && typeof req.body === "object") return req.body;
  if (typeof req.body === "string") {
    try { return JSON.parse(req.body); } catch { return {}; }
  }
  return {};
}

function tokenSubject(token) {
  try {
    const part = token.split(".")[1];
    if (!part) return "";
    const normalized = part.replace(/-/g, "+").replace(/_/g, "/");
    const json = Buffer.from(normalized, "base64").toString("utf8");
    return String(JSON.parse(json).sub || "").slice(0, 128);
  } catch {
    return "";
  }
}

function needsResearch(message, mode) {
  return mode === "web-research" || mode === "parts" || WEB_SIGNAL.test(String(message || ""));
}

async function firebaseChat(token, body) {
  const response = await fetch(`${FIREBASE_API}/chat`, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json"
    },
    body: JSON.stringify(body)
  });
  const text = await response.text();
  let data = {};
  try { data = JSON.parse(text); } catch { data = { error: text || "Chill Bro backend returned an unreadable response." }; }
  return { response, data };
}

function normalizeSources(result) {
  const items = [];
  for (const source of result?.sources || []) {
    if (!source) continue;
    const url = source.url || source.source?.url || null;
    const title = source.title || source.source?.title || url || "Web source";
    if (url) items.push({ type: "web", title, url });
  }

  for (const step of result?.steps || []) {
    for (const toolResult of step?.toolResults || []) {
      let serialized = "";
      try { serialized = JSON.stringify(toolResult?.output || toolResult); } catch { serialized = ""; }
      const urls = serialized.match(/https?:\\?\/\\?\/[^"'\s}]+/g) || [];
      for (const raw of urls) {
        const url = raw.replace(/\\\//g, "/").replace(/[),.;]+$/, "");
        items.push({ type: "web", title: url, url });
      }
    }
  }

  const seen = new Set();
  return items.filter((item) => {
    const key = item.url || item.title;
    if (!key || seen.has(key)) return false;
    seen.add(key);
    return true;
  }).slice(0, 10);
}

export default async function handler(req, res) {
  res.setHeader("Cache-Control", "no-store");
  res.setHeader("X-Content-Type-Options", "nosniff");

  if (req.method !== "POST") {
    res.setHeader("Allow", "POST");
    return res.status(405).json({ error: "Method not allowed." });
  }

  const token = bearer(req);
  if (!token) return res.status(401).json({ error: "Authentication required." });

  const body = parseBody(req);
  const message = String(body.message || "").trim();
  const mode = String(body.mode || "field-help").slice(0, 40);

  if (!message) return res.status(400).json({ error: "A text request is required for live research." });
  if (message.length > 12000) return res.status(400).json({ error: "Message is too long." });
  if (body.imageDataUrl) return res.status(413).json({ error: "Send the field photo to Chill Bro first, then ask a text follow-up for live research." });

  const baseline = await firebaseChat(token, body).catch(() => null);
  if (!baseline) return res.status(502).json({ error: "Chill Bro's authenticated field service is unavailable." });
  if (!baseline.response.ok) {
    const status = [400, 401, 403].includes(baseline.response.status) ? baseline.response.status : 502;
    return res.status(status).json({ error: baseline.data.error || "Chill Bro authentication or field context failed." });
  }

  if (!needsResearch(message, mode)) {
    return res.status(200).json({
      ...baseline.data,
      sources: baseline.data.sources || [],
      boodaFlow: {
        ...(baseline.data.boodaFlow || {}),
        route: baseline.data.boodaFlow?.route || mode,
        usedWeb: false,
        hybridGateway: true
      }
    });
  }

  const contextText = JSON.stringify(body.context || {}).slice(0, 10000);
  const baselineText = String(baseline.data.answer || "").slice(0, 7000);
  const userId = tokenSubject(token) || String(baseline.data.role || "staff");

  try {
    const result = await generateText({
      model: "openai/gpt-5.6-terra",
      system: SYSTEM_PROMPT,
      prompt: `AUTHENTICATED ROLE: ${baseline.data.role || "staff"}\nMODE: ${mode}\n\nAPP/FIELD CONTEXT:\n${contextText || "No additional page context."}\n\nINTERNAL/NATIVE BASELINE:\n${baselineText || "No baseline answer available."}\n\nTECH REQUEST:\n${message}`,
      maxOutputTokens: 1600,
      toolChoice: "required",
      tools: {
        oem_search: gateway.tools.exaSearch({
          type: "fast",
          numResults: 8,
          includeDomains: TRUSTED_DOMAINS,
          contents: { highlights: true }
        }),
        broad_search: gateway.tools.exaSearch({
          type: "fast",
          numResults: 6,
          contents: { highlights: true }
        })
      },
      providerOptions: {
        gateway: {
          user: userId,
          tags: ["feature:chill-bro", "route:web-research"],
          disallowPromptTraining: true
        }
      }
    });

    const answer = String(result.text || "").trim();
    if (!answer) throw new Error("Research gateway returned no text.");

    return res.status(200).json({
      ...baseline.data,
      answer,
      sources: normalizeSources(result),
      researchFallback: false,
      boodaFlow: {
        ...(baseline.data.boodaFlow || {}),
        route: mode === "parts" ? "parts+web" : "web-research",
        model: "gpt-5.6-terra",
        usedWeb: true,
        hybridGateway: true,
        stages: [
          "firebase_employee_auth",
          "internal_native_baseline",
          "trusted_oem_web_search",
          "broader_web_if_needed",
          "source_reconciliation",
          "field_answer"
        ]
      }
    });
  } catch (error) {
    console.error("Chill Bro live research fallback", error?.message || error);
    return res.status(200).json({
      ...baseline.data,
      sources: baseline.data.sources || [],
      researchFallback: true,
      researchWarning: "Live web research was unavailable, so Chill Bro returned the authenticated internal baseline.",
      boodaFlow: {
        ...(baseline.data.boodaFlow || {}),
        route: baseline.data.boodaFlow?.route || mode,
        usedWeb: false,
        hybridGateway: true,
        webResearchFailedSafely: true
      }
    });
  }
}
